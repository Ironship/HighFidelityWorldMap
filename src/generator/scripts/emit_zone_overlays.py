"""Emit ZoneOverlays.lua: how many exploration overlays each zone map has.

The client's C_MapExplorationInfo.GetExploredMapTextures(uiMapID) returns one
entry per overlay the player has discovered, but nothing says how many there
are in total. This bakes that total (WorldMapOverlay, grouped by the zone's
UiMapArt) so the addon can call a zone fully explored when the two counts
match -- see ZoneFog.lua. Overlays are counted by distinct geometry, the same
key the addon dedupes the client's entries by.

    python3 scripts/emit_zone_overlays.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from hfwm.config.tiles import UI_MAP_TYPE_ZONE  # noqa: E402
from hfwm.gamedata.tables import fetch_pinned_table  # noqa: E402

OUT = ROOT.parents[0] / "addon" / "client" / "ZoneOverlays.lua"


def overlay_counts():
    """UiMapID -> (name, overlay count) for every zone map that has overlays."""
    ui_maps = fetch_pinned_table("UiMap")
    xart = fetch_pinned_table("UiMapXMapArt")
    overlays = fetch_pinned_table("WorldMapOverlay")

    shapes = {}  # UiMapArtID -> {(offX, offY, w, h)}
    for o in overlays:
        shapes.setdefault(o["UiMapArtID"], set()).add(
            (o["OffsetX"], o["OffsetY"], o["TextureWidth"], o["TextureHeight"]))

    arts = {}  # UiMapID -> {UiMapArtID}; PhaseID 0 only, phased art is not the base map
    for r in xart:
        if r["PhaseID"] == "0":
            arts.setdefault(r["UiMapID"], set()).add(r["UiMapArtID"])

    out = {}
    for m in ui_maps:
        if int(m["Type"]) != UI_MAP_TYPE_ZONE:
            continue
        found = set().union(*(shapes.get(a, set()) for a in arts.get(m["ID"], ())))
        if found:
            out[int(m["ID"])] = (m["Name_lang"], len(found))
    return out


def main():
    lines = ["-- Auto-generated by scripts/emit_zone_overlays.py - DO NOT EDIT",
             "-- UiMapID -> number of exploration overlays on that zone map.",
             "HFWMF_ZONE_OVERLAYS = {"]
    counts = overlay_counts()
    for uid in sorted(counts):
        name, n = counts[uid]
        lines.append(f"    [{uid}] = {n},  -- {name}")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(counts)} zones -> {OUT}")


if __name__ == "__main__":
    main()
