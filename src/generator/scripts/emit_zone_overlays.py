"""Emit ZoneOverlays.lua and ZoneOverlayTiles.lua.

ZoneOverlays.lua: how many exploration overlays each zone map has.

The client's C_MapExplorationInfo.GetExploredMapTextures(uiMapID) returns one
entry per overlay the player has discovered, but nothing says how many there
are in total. This bakes that total (WorldMapOverlay, grouped by the zone's
UiMapArt) so the addon can call a zone fully explored when the two counts
match -- see ZoneFog.lua. Overlays are counted by distinct geometry, the same
key the addon dedupes the client's entries by.

ZoneOverlayTiles.lua: the same overlays in full (geometry plus the tile
FileDataIDs, row-major), so Exploration.lua can draw the ones the player has
NOT discovered when Fog of War is off and the native map has to match the HD
one.

    python3 scripts/emit_zone_overlays.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from hfwm.config.tiles import UI_MAP_TYPE_ZONE  # noqa: E402
from hfwm.gamedata.tables import fetch_pinned_table  # noqa: E402

CLIENT = ROOT.parents[0] / "addon" / "client"
OUT = CLIENT / "ZoneOverlays.lua"
OUT_TILES = CLIENT / "ZoneOverlayTiles.lua"


def zone_overlays():
    """UiMapID -> (name, {geometry: (cols, fileDataIDs)}) for every zone map
    that has overlays. geometry is (offsetX, offsetY, width, height);
    fileDataIDs are row-major, `cols` per row."""
    ui_maps = fetch_pinned_table("UiMap")
    xart = fetch_pinned_table("UiMapXMapArt")
    overlays = fetch_pinned_table("WorldMapOverlay")
    tiles = fetch_pinned_table("WorldMapOverlayTile")

    by_overlay = {}  # WorldMapOverlayID -> {(row, col): fdid}
    for t in tiles:
        by_overlay.setdefault(t["WorldMapOverlayID"], {})[
            (int(t["RowIndex"]), int(t["ColIndex"]))] = int(t["FileDataID"])

    shapes = {}  # UiMapArtID -> {(offX, offY, w, h): (cols, fdids)}
    for o in overlays:
        geom = (int(o["OffsetX"]), int(o["OffsetY"]),
                int(o["TextureWidth"]), int(o["TextureHeight"]))
        grid = by_overlay.get(o["ID"], {})
        cols = 1 + max((c for _, c in grid), default=-1)
        rows = 1 + max((r for r, _ in grid), default=-1)
        fdids = [grid.get((r, c), 0) for r in range(rows) for c in range(cols)]
        shapes.setdefault(o["UiMapArtID"], {}).setdefault(geom, (cols, fdids))

    arts = {}  # UiMapID -> {UiMapArtID}; PhaseID 0 only, phased art is not the base map
    for r in xart:
        if r["PhaseID"] == "0":
            arts.setdefault(r["UiMapID"], set()).add(r["UiMapArtID"])

    out = {}
    for m in ui_maps:
        if int(m["Type"]) != UI_MAP_TYPE_ZONE:
            continue
        found = {}
        for a in sorted(arts.get(m["ID"], ())):
            for geom, v in shapes.get(a, {}).items():
                found.setdefault(geom, v)
        if found:
            out[int(m["ID"])] = (m["Name_lang"], found)
    return out


def main():
    zones = zone_overlays()

    lines = ["-- Auto-generated by scripts/emit_zone_overlays.py - DO NOT EDIT",
             "-- UiMapID -> number of exploration overlays on that zone map.",
             "HFWMF_ZONE_OVERLAYS = {"]
    for uid in sorted(zones):
        name, found = zones[uid]
        lines.append(f"    [{uid}] = {len(found)},  -- {name}")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(zones)} zones -> {OUT}")

    lines = ["-- Auto-generated by scripts/emit_zone_overlays.py - DO NOT EDIT",
             "-- UiMapID -> every exploration overlay of that zone map:",
             "-- { offsetX, offsetY, width, height, tileColumns, { FileDataID... } }",
             "HFWMF_ZONE_OVERLAY_TILES = {"]
    for uid in sorted(zones):
        name, found = zones[uid]
        lines.append(f"    [{uid}] = {{  -- {name}")
        for (x, y, w, h), (cols, fdids) in sorted(found.items()):
            ids = ",".join(map(str, fdids))
            lines.append(f"        {{{x},{y},{w},{h},{cols},{{{ids}}}}},")
        lines.append("    },")
    lines.append("}")
    OUT_TILES.write_text("\n".join(lines) + "\n")
    print(f"{len(zones)} zones -> {OUT_TILES}")


if __name__ == "__main__":
    main()
