"""What every generated Lua file shares: the banner, and reading what was
there before so hand-added data can be carried across a regeneration."""

from __future__ import annotations

import time
from pathlib import Path

AUTOGEN_NOTICE = "-- Auto-generated by generateHFWM.py - DO NOT EDIT\n"


def generated_stamp() -> str:
    """The ``-- Generated: <timestamp>`` banner line."""
    return f"-- Generated: {time.strftime('%Y-%m-%d %H:%M:%S')}\n"


def read_existing(path: Path) -> str:
    """Return *path*'s current text, or ``""`` if it is absent or unreadable.

    Generators call this *before* overwriting their output, so hand-added
    entries (see :data:`hfwm.config.interior.SYNTHETIC_FDID_BASE`) can be
    restored rather than silently reverted.
    """
    if not path.is_file():
        return ""
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return ""


def mask_comments_and_strings(text: str) -> str:
    """Return *text* with comment and string-literal contents blanked out
    (same length, same newlines), so brace-depth scanning never miscounts
    a stray ``{``/``}`` that only appears in prose or a path string.
    """
    out = list(text)
    i, n = 0, len(text)
    in_comment = False
    in_string = False
    while i < n:
        ch = text[i]
        if in_comment:
            if ch != "\n":
                out[i] = " "
            else:
                in_comment = False
            i += 1
            continue
        if in_string:
            if ch == '"':
                in_string = False
            elif ch == "\\" and i + 1 < n:
                out[i] = " "
                out[i + 1] = " "
                i += 2
                continue
            else:
                out[i] = " "
            i += 1
            continue
        if ch == "-" and i + 1 < n and text[i + 1] == "-":
            in_comment = True
            i += 2
            continue
        if ch == '"':
            in_string = True
            i += 1
            continue
        i += 1
    return "".join(out)
